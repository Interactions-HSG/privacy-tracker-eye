// Regenerate the bundled tracker list from the open-source Disconnect list.
// -----------------------------------------------------------------------------
//   npm run import:trackers
//
// Downloads disconnectme/disconnect-tracking-protection services.json and emits
// src/data/trackers.generated.ts, a drop-in replacement for src/data/trackers.ts
// with the full upstream coverage (thousands of domains). To activate it, change
// the two imports of "../data/trackers" (in src/background/tracker-engine.ts and
// anywhere else) to "../data/trackers.generated".
//
// Disconnect list license: the CODE is GPL-3.0; the LIST (services.json) is
// distributed under CC BY-NC-SA 4.0 with a GPL-3.0 alternative. Review the
// upstream LICENSE before redistributing a build that bundles it.

import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const SRC =
  "https://raw.githubusercontent.com/disconnectme/disconnect-tracking-protection/master/services.json";

// Disconnect category -> our TrackerCategory.
const CATEGORY_MAP = {
  Advertising: "advertising",
  Analytics: "analytics",
  Social: "social",
  Content: "content",
  Cryptomining: "cryptomining",
  FingerprintingInvasive: "fingerprinting",
  FingerprintingGeneral: "fingerprinting",
  Disconnect: "unknown",
};

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

console.log(`[import] fetching ${SRC}`);
const res = await fetch(SRC);
if (!res.ok) throw new Error(`fetch failed: ${res.status} ${res.statusText}`);
const data = await res.json();

/** @type {Record<string, [string, string]>} */
const out = {};
for (const [disCat, entries] of Object.entries(data.categories ?? {})) {
  const category = CATEGORY_MAP[disCat];
  if (!category) continue; // skip categories we don't model (e.g. Email)
  for (const entry of entries) {
    for (const [org, hosts] of Object.entries(entry)) {
      // hosts is { homepageUrl: [domain, domain, ...] }
      for (const domains of Object.values(hosts)) {
        if (!Array.isArray(domains)) continue;
        for (const d of domains) {
          const domain = String(d).toLowerCase().replace(/^www\./, "");
          // Keep the first (most invasive categories iterate first by file order);
          // do not overwrite an existing stronger classification.
          if (!out[domain]) out[domain] = [org, category];
        }
      }
    }
  }
}

const count = Object.keys(out).length;
const body = `// AUTO-GENERATED by scripts/import-trackers.mjs from the Disconnect list.
// Do not edit by hand. Source: ${SRC}
// Disconnect list license: GPL-3.0 (code) / CC BY-NC-SA 4.0 (list).

import type { TrackerCategory, TrackerHit } from "../shared/types";

type Row = [organization: string, category: TrackerCategory];

const RAW: Record<string, Row> = ${JSON.stringify(out, null, 2)};

const TRACKERS: Map<string, TrackerHit> = new Map(
  Object.entries(RAW).map(([domain, [organization, category]]) => [
    domain,
    { domain, organization, category },
  ]),
);

export const TRACKER_COUNT = TRACKERS.size;

export function lookupTracker(registrableDomain: string | null): TrackerHit | undefined {
  if (!registrableDomain) return undefined;
  return TRACKERS.get(registrableDomain);
}
`;

const dest = resolve(root, "src/data/trackers.generated.ts");
await writeFile(dest, body, "utf8");
console.log(`[import] wrote ${count} tracker domains -> ${dest}`);
console.log('[import] activate by importing "../data/trackers.generated" instead of "../data/trackers".');
